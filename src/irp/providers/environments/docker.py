"""Docker images: the isolated option for running a stranger's code.

IRP writes a small Dockerfile, builds it with your existing Docker, and
records the image ID, the resolved base image digest and the package lock taken
from inside the image. Runs then mount only the study's code directory.
"""

from __future__ import annotations

import json
import os
import secrets
import shutil
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path

from irp.domain.errors import ErrorCode, IRPError
from irp.identity import PRODUCT

BUILD_TIMEOUT_S = 3600


@dataclass(frozen=True)
class DockerEnvironment:
    tag: str
    image_id: str
    base_image: str
    base_digest: str | None
    dockerfile: str
    python_version: str
    lock_text: str
    docker_version: str


def docker_executable() -> str | None:
    configured = os.environ.get("IRP_DOCKER")
    if configured:
        return configured if Path(configured).is_file() else None
    return shutil.which("docker")


def docker_status() -> tuple[bool, str]:
    """(daemon reachable, detail). Never starts or configures Docker."""
    docker = docker_executable()
    if docker is None:
        return False, "docker is not on PATH"
    try:
        result = subprocess.run(
            [docker, "version", "--format", "{{.Server.Version}}"],
            capture_output=True,
            text=True,
            timeout=20,
            check=False,
        )
    except (OSError, subprocess.TimeoutExpired) as exc:
        return False, f"docker did not answer: {exc}"
    if result.returncode != 0:
        return False, (result.stderr.strip() or "the Docker daemon is not reachable")[:400]
    return True, result.stdout.strip()


def render_dockerfile(
    *, base_image: str, system_packages: list[str], has_requirements: bool, packages: list[str]
) -> str:
    lines = [
        f"# Generated by {PRODUCT.display_name} {PRODUCT.version}. Rebuild with the same base digest",
        "# and requirements to reproduce this environment.",
        f"FROM {base_image}",
        "ENV PYTHONDONTWRITEBYTECODE=1 PIP_NO_CACHE_DIR=1 PIP_DISABLE_PIP_VERSION_CHECK=1 HOME=/tmp",
    ]
    if system_packages:
        joined = " ".join(sorted(set(system_packages)))
        lines.append(
            "RUN apt-get update && apt-get install -y --no-install-recommends "
            f"{joined} && rm -rf /var/lib/apt/lists/*"
        )
    if has_requirements:
        lines.append("COPY requirements.txt /tmp/irp-requirements.txt")
        lines.append("RUN python -m pip install -r /tmp/irp-requirements.txt")
    if packages:
        quoted = " ".join(json.dumps(p) for p in packages)
        lines.append(f"RUN python -m pip install {quoted}")
    lines.append("RUN python -m pip freeze > /irp-lock.txt")
    lines.append("WORKDIR /work")
    return "\n".join(lines) + "\n"


def _docker(args: list[str], *, timeout: int, what: str, cwd: Path | None = None) -> str:
    docker = docker_executable()
    if docker is None:
        raise IRPError(
            ErrorCode.PROVIDER_UNAVAILABLE,
            "docker is not on PATH.",
            remediation="Install Docker and start it, or use backend='uv'. IRP does not install Docker.",
        )
    try:
        result = subprocess.run(
            [docker, *args], cwd=cwd, capture_output=True, text=True, timeout=timeout, check=False
        )
    except subprocess.TimeoutExpired as exc:
        raise IRPError(ErrorCode.TIMEOUT, f"{what} did not finish within {timeout} s.") from exc
    if result.returncode != 0:
        raise IRPError(
            ErrorCode.EXECUTION_FAILURE,
            f"{what} failed with exit code {result.returncode}.",
            remediation="Read the build output; fix the base image or requirement that failed.",
            details={"stderr": result.stderr[-4000:], "stdout": result.stdout[-2000:]},
        )
    return result.stdout


def build_docker_environment(
    *,
    context_dir: Path,
    tag: str,
    base_image: str,
    requirements: Path | None,
    packages: list[str],
    system_packages: list[str],
) -> DockerEnvironment:
    available, detail = docker_status()
    if not available:
        raise IRPError(
            ErrorCode.PROVIDER_UNAVAILABLE,
            f"Docker is not available: {detail}",
            remediation="Start Docker (or install it), then retry; or use backend='uv'.",
        )
    if context_dir.exists():
        raise IRPError(
            ErrorCode.INVALID_REQUEST,
            f"The environment directory {context_dir} already exists.",
            remediation="Choose a new environment name; environments are never rebuilt in place.",
        )
    context_dir.mkdir(parents=True)
    if requirements is not None:
        shutil.copyfile(requirements, context_dir / "requirements.txt")
    dockerfile = render_dockerfile(
        base_image=base_image,
        system_packages=system_packages,
        has_requirements=requirements is not None,
        packages=packages,
    )
    (context_dir / "Dockerfile").write_text(dockerfile, encoding="utf-8")
    _docker(["pull", base_image], timeout=BUILD_TIMEOUT_S, what=f"Pulling {base_image}")
    digests = json.loads(
        _docker(
            ["image", "inspect", "--format", "{{json .RepoDigests}}", base_image],
            timeout=60,
            what="Inspecting the base image",
        )
        or "null"
    )
    base_digest = digests[0] if digests else None
    _docker(
        ["build", "--tag", tag, str(context_dir)],
        timeout=BUILD_TIMEOUT_S,
        what="Building the image",
    )
    image_id = _docker(
        ["image", "inspect", "--format", "{{.Id}}", tag], timeout=60, what="Inspecting the image"
    ).strip()
    lock_text = _docker(
        ["run", "--rm", "--network", "none", tag, "cat", "/irp-lock.txt"],
        timeout=300,
        what="Reading the lock",
    )
    python_version = _docker(
        [
            "run",
            "--rm",
            "--network",
            "none",
            tag,
            "python",
            "-c",
            "import sys; print('.'.join(map(str, sys.version_info[:3])))",
        ],
        timeout=300,
        what="Reading the Python version",
    ).strip()
    return DockerEnvironment(
        tag=tag,
        image_id=image_id,
        base_image=base_image,
        base_digest=base_digest,
        dockerfile=dockerfile,
        python_version=python_version,
        lock_text=lock_text,
        docker_version=docker_status()[1],
    )


def verify_mount(image: str, code_dir: Path) -> None:
    """Prove the container sees code/: Docker VMs (Colima, Docker Desktop) share only some host folders.

    Without this, an unshared path mounts as an empty /work and the run fails
    with a misleading "file not found".
    """
    token = secrets.token_hex(16)
    marker = code_dir / ".irp-mount-check"
    marker.write_text(token, encoding="utf-8")
    try:
        seen = _docker(
            [
                "run",
                "--rm",
                "--network",
                "none",
                "-v",
                f"{code_dir}:/work",
                image,
                "cat",
                "/work/.irp-mount-check",
            ],
            timeout=120,
            what="Checking the code directory mount",
        ).strip()
    except IRPError:
        seen = ""
    finally:
        marker.unlink(missing_ok=True)
    if seen != token:
        raise IRPError(
            ErrorCode.PROVIDER_UNAVAILABLE,
            f"Docker cannot see {code_dir}: the container's /work is empty.",
            remediation="Your Docker VM shares only some host folders (Colima shares your home "
            "directory by default). Move the study under a shared folder, or add this path to the "
            "VM's mounts, then retry.",
            details={"code_dir": str(code_dir)},
        )


def docker_run_command(
    *,
    image: str,
    code_dir: Path,
    workdir: str,
    command: str,
    env: dict[str, str],
    network: bool,
    gpu: bool,
    memory_limit: str | None,
) -> list[str]:
    """The exact `docker run` argument list; recorded in evidence as the run's launcher."""
    docker = docker_executable() or "docker"
    args = [
        docker,
        "run",
        "--rm",
        "--init",
        "-v",
        f"{code_dir}:/work",
        "-w",
        f"/work/{workdir}".rstrip("/"),
    ]
    if sys.platform != "win32" and hasattr(os, "getuid"):
        args += ["--user", f"{os.getuid()}:{os.getgid()}"]
    if not network:
        args += ["--network", "none"]
    if gpu:
        args += ["--gpus", "all"]
    if memory_limit:
        args += ["--memory", memory_limit]
    for key, value in sorted(env.items()):
        args += ["-e", f"{key}={value}"]
    args += [image, "sh", "-c", command]
    return args

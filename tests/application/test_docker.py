"""Docker environment lane: a real image build and an isolated run.

Runs only with IRP_TEST_DOCKER=1 and a reachable daemon (the CI docker lane).
"""

import os
import sys

import pytest

from irp.providers.environments.docker import docker_status
from tests.conftest import REAL_HOME, call

pytestmark = [
    pytest.mark.docker,
    pytest.mark.skipif(os.environ.get("IRP_TEST_DOCKER") != "1", reason="set IRP_TEST_DOCKER=1"),
]


@pytest.fixture(autouse=True)
def _real_docker_context(monkeypatch):
    """The isolated HOME hides ~/.docker; keep the person's Docker context (Colima, remote, Desktop)."""
    config = REAL_HOME / ".docker"
    if config.is_dir() and "DOCKER_CONFIG" not in os.environ:
        monkeypatch.setenv("DOCKER_CONFIG", str(config))


def test_docker_environment_and_isolated_run(coded):
    available, detail = docker_status()
    if not available:
        pytest.skip(f"Docker unavailable: {detail}")
    if os.environ.get("IRP_TEST_DOCKER_DIR") is None and sys.platform == "darwin":
        pytest.skip(
            "macOS Docker VMs share only some folders; set IRP_TEST_DOCKER_DIR to a shared directory"
        )
    (coded / "code" / "requirements.txt").write_text("")
    env = call("create_env", {"study": str(coded), "backend": "docker", "python": "3.12"})["env"]
    assert env["isolation"] == "container"
    assert env["image_id"].startswith("sha256:")
    assert env["base_image"] == "python:3.12-slim"
    assert env["python"].startswith("3.12")
    assert (coded / env["dockerfile"]).read_text().startswith("# Generated by IRP")

    result = call(
        "run",
        {"study": str(coded), "command": "python ols.py", "seed": 0, "network": False},
    )
    assert result["status"] == "succeeded", result
    assert result["outputs"] == ["code/results.json"]
    measured = call(
        "extract_metrics",
        {"study": str(coded), "run_id": "r1", "specs": [{"name": "slope", "key": "slope"}]},
    )["measurements"][0]["value"]
    assert abs(measured - 2.0) < 0.02

    probe = call(
        "run",
        {
            "study": str(coded),
            "command": "python -c \"import urllib.request; urllib.request.urlopen('https://pypi.org', timeout=5)\"",
            "network": False,
            "scope": "smoke",
        },
    )
    assert probe["status"] == "failed", "network=false must block network access"
    assert call("verify", {"study": str(coded)})["ok"] is True
